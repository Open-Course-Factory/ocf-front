/**
 * A lab in the learner's browser that offers apps shows unkernel's desktop in
 * the console's place. Its launcher lists the apps the scenario offers and
 * nothing else (no games), the page asks no outside site for its wallpaper,
 * the step's foreground script and a pasted command land in the desktop's
 * terminal, and « Vérifier » checks what the learner did there.
 *
 * Needs the desktop page under public/unkernel-desktop/ (local-machine-image,
 * desktop/build.sh).
 */

const API = process.env.OCF_API_URL || 'http://localhost:8080/api/v1';
const LEARNER_EMAIL = process.env.E2E_USER || 'karim@test.ocf';
const PASSWORD = process.env.E2E_PASS || 'OcfTest2026!';
const STAMP = Date.now().toString(36);
const TITLE = `E2E local desktop ${STAMP}`;
const TITLE_RELOAD = `E2E local desktop reload ${STAMP}`;

let admin: ApiSession | null = null;

// The desktop page's terminals (its KW.windows); the learner's is the one
// the run page opens once the run is built, named "lab".
type Terminals = { list(): { n: number; name: string }[]; send(n: number, d: string): void; text(n: number): string };

// Type a line into the desktop's learner terminal.
async function typeOnDesktop(page: Page, line: string): Promise<void> {
  await page.evaluate((text) => {
    const frame = document.querySelector('iframe.ocf-desktop-frame') as HTMLIFrameElement;
    const t = (frame.contentWindow as unknown as { KW: { windows: Terminals } }).KW.windows;
    t.send(t.list().find(w => w.name === 'lab')!.n, text);
  }, `${line}\r`);
}

// What the desktop's learner terminal shows ('' until it is open).
function desktopText(page: Page): Promise<string> {
  return page.evaluate(() => {
    const frame = document.querySelector('iframe.ocf-desktop-frame') as HTMLIFrameElement | null;
    const t = (frame?.contentWindow as unknown as { KW?: { windows?: Terminals } } | null)?.KW?.windows;
    const lab = t?.list().find(w => w.name === 'lab');
    return lab ? t!.text(lab.n) : '';
  });
}

// Whether a command exists in the desktop's machine (run as root, as checks are).
function onDesktopMachine(page: Page, command: string): Promise<boolean> {
  return page.evaluate(async (cmd) => {
    const frame = document.querySelector('iframe.ocf-desktop-frame') as HTMLIFrameElement;
    type Vm = { exec(f: string, a: string[], o: object): Promise<{ exitCode: number | null }> };
    const vm = await (frame.contentWindow as unknown as { KW: { ready(): Promise<Vm> } }).KW.ready();
    const r = await vm.exec('sh', ['-c', `command -v ${cmd}`], { user: 'root', signal: AbortSignal.timeout(10_000), maxBuffer: 4096 });
    return r.exitCode === 0;
  }, command);
}
let learner: ApiSession;
const scenarioIds: string[] = [];
let planId = '';
let planSettingBefore = 'off';
// The desktop runs only when both platform switches are on.
const FLAG_KEYS = ['local_machines', 'local_machine_desktop'];
const flagsBefore: { id: string; enabled: boolean }[] = [];

test.beforeAll(async () => {
  admin = await adminSession();
  learner = await apiLogin(LEARNER_EMAIL, PASSWORD);
  if (!admin) return;
  const asAdmin = { Authorization: `Bearer ${admin.token}` };

  for (const key of FLAG_KEYS) {
    const flags = await admin.api.get(`${API}/features?key=${key}`, { headers: asAdmin });
    const flag = (await flags.json()).data.find((f: { key: string }) => f.key === key);
    flagsBefore.push({ id: flag.id, enabled: flag.enabled });
    expect((await admin.api.patch(`${API}/features/${flag.id}`, { headers: asAdmin, data: { enabled: true } })).ok()).toBeTruthy();
  }

  const current = await learner.api.get(`${API}/user-subscriptions/current`, { headers: { Authorization: `Bearer ${learner.token}` } });
  const subscription = await current.json();
  planId = subscription.subscription_plan_id;
  planSettingBefore = subscription.subscription_plan?.local_machines || 'off';
  expect((await admin.api.patch(`${API}/subscription-plans/${planId}`, { headers: asAdmin, data: { local_machines: 'allowed' } })).ok()).toBeTruthy();

  scenarioIds.push((await importScenario(admin, null, {
    title: TITLE,
    description: 'Auto-generated by local-machine-desktop.spec.ts — safe to delete.',
    is_public: true,
    machine: 'local',
    machine_display: 'desktop',
    machine_apps: ['python', 'nvim'],
    steps: [{
      title: 'Écrire depuis le bureau',
      step_type: 'terminal',
      text_content: 'Dans le terminal du bureau, lancez `echo bureau > /tmp/bureau.txt`{{exec}}.',
      // The learner's shell is root's, opened after the build: it sees what the build left.
      background_script: 'echo built > /tmp/built.txt',
      foreground_script: 'echo PRET-42; whoami; cat /tmp/built.txt',
      verify_script: 'grep -qx bureau /tmp/bureau.txt || { echo "/tmp/bureau.txt manque"; exit 1; }',
    }],
  })).id);

  // A reload boots a new desktop: the step's world comes back through the
  // rebuild (its background script), the learner's own file does not.
  scenarioIds.push((await importScenario(admin, null, {
    title: TITLE_RELOAD,
    description: 'Auto-generated by local-machine-desktop.spec.ts — safe to delete.',
    is_public: true,
    machine: 'local',
    machine_display: 'desktop',
    machine_apps: ['python'],
    steps: [{
      title: 'Garder le monde',
      step_type: 'terminal',
      text_content: 'Écrivez `moi` dans le fichier `/tmp/moi.txt`, puis cliquez sur « Vérifier ».',
      background_script: 'echo monde > /tmp/monde.txt',
      verify_script: 'test -f /tmp/monde.txt || { echo "le monde manque"; exit 1; }; grep -qx moi /tmp/moi.txt || { echo "/tmp/moi.txt manque"; exit 1; }',
    }],
  })).id);
});

// One live run in the browser per learner: whatever a test leaves, ended or
// failed, must not refuse the next test's launch.
test.afterEach(async () => {
  await endLocalRuns(learner);
})

test.afterAll(async () => {
  if (!admin) return;
  for (const s of await getMyScenarioSessions(learner)) {
    if (scenarioIds.includes(s.scenario_id)) await cleanupScenarioSession(learner, s.id);
  }
  for (const id of scenarioIds) await deleteScenarioById(admin, id);
  const asAdmin = { Authorization: `Bearer ${admin.token}` };
  await admin.api.patch(`${API}/subscription-plans/${planId}`, { headers: asAdmin, data: { local_machines: planSettingBefore } });
  for (const { id, enabled } of flagsBefore) await admin.api.patch(`${API}/features/${id}`, { headers: asAdmin, data: { enabled } });
});

test('a lab that offers apps shows the desktop, with only those apps to install', async ({ page }, info) => {
  test.skip(!admin, 'needs the platform admin to set up the lab');
  test.setTimeout(10 * 60 * 1000);
  const shot = (name: string) => page.screenshot({ path: info.outputPath(`${name}.png`) });
  // Every request of the desktop page goes to the front or the API: none to
  // an outside site. (The front's own page is another matter.)
  const ours = new Set([new URL(API).host, new URL(info.project.use.baseURL!).host]);
  const outside: string[] = [];
  page.on('request', r => {
    let fromDesktop = true; // a worker's request has no frame: the desktop's kernel
    try { fromDesktop = r.frame().url().includes('/unkernel-desktop/'); } catch { /* worker */ }
    const url = new URL(r.url());
    if (fromDesktop && /^(https?|wss?):$/.test(url.protocol) && !ours.has(url.host)) outside.push(r.url());
  });

  await login(page, LEARNER_EMAIL, PASSWORD);
  await dismissVerificationBanner(page);
  await navigateViaMenuCategory(page, 'scenarios', '/scenarios');
  const card = page.getByTestId('scenario-card').filter({ hasText: TITLE });
  await expect(card).toBeVisible({ timeout: 15_000 });
  await card.getByTestId('scenario-launch-btn').click();
  await page.waitForURL(/\/terminal-session\//, { timeout: 240_000 });

  const verify = page.getByTestId('scenario-verify-btn');
  await expect(verify).toBeEnabled({ timeout: 300_000 });
  const desktop = page.frameLocator('iframe.ocf-desktop-frame');
  await expect(desktop.locator('#win-terminal-1')).toBeVisible({ timeout: 120_000 });
  // The step's foreground script is typed into the learner's terminal, a
  // login shell of the run's user (root here) opened after the build.
  await expect.poll(() => desktopText(page), { timeout: 60_000 }).toContain('PRET-42');
  await expect.poll(() => desktopText(page)).toMatch(/^root\s*$/m);
  await expect.poll(() => desktopText(page)).toMatch(/^built\s*$/m);
  // The scenario asks for size xs (the seed's default): the machine gets at
  // least 1 GiB, as ocf-core says.
  const pageSearch = await page.evaluate(() => (document.querySelector('iframe.ocf-desktop-frame') as HTMLIFrameElement)
    .contentWindow!.location.search);
  expect(new URLSearchParams(pageSearch).get('mem')).toBe('1024');
  await shot('1-desktop');

  // Full screen puts the desktop's iframe on the whole screen; leaving it
  // gives the run page back.
  await page.getByTestId('desktop-fullscreen').click();
  await expect.poll(() => page.evaluate(() => document.fullscreenElement?.className ?? '')).toBe('ocf-desktop-frame');
  await page.evaluate(() => document.exitFullscreen());
  await expect.poll(() => page.evaluate(() => document.fullscreenElement === null)).toBe(true);

  await desktop.locator('#win-terminal-1 .wm-body').click();
  await page.keyboard.press('Control+Shift+O');
  // The launcher shows the page's own apps and a folder per group that has an
  // offered app: Tools (Neovim) and Runtimes (Python), and no other group.
  const tile = (name: string) => desktop.getByText(name, { exact: true });
  await expect(tile('Runtimes')).toBeVisible({ timeout: 10_000 });
  await expect(tile('Tools')).toBeVisible();
  for (const absent of ['Games', 'Browsers', 'Agents', 'Media', 'Servers']) {
    await expect(tile(absent)).toHaveCount(0);
  }
  await shot('2-launcher');
  // Its search finds an offered app, and nothing for a game. Escape clears
  // the search and keeps the launcher open.
  const search = desktop.getByPlaceholder('Search');
  await page.keyboard.type('python');
  await expect(tile('Python')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(search).toHaveValue('');
  await page.keyboard.type('doom');
  await expect(search).toHaveValue('doom');
  await expect(tile('Doom')).toHaveCount(0);
  await expect(desktop.getByText('Nothing matches')).toBeVisible();
  await shot('3-no-doom');
  // The first Escape clears the search, the second closes the launcher.
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');
  await expect(desktop.getByPlaceholder('Search')).toHaveCount(0);

  // An offered app that is not in the image installs from the launcher (apt
  // through the platform's mirror, with the desktop user's sudo).
  expect(await onDesktopMachine(page, 'nvim')).toBe(false);
  await page.keyboard.press('Control+Shift+O');
  await page.keyboard.type('neovim');
  await tile('Neovim').click();
  await expect.poll(() => onDesktopMachine(page, 'nvim'), { timeout: 240_000, intervals: [5_000] }).toBe(true);
  await shot('3b-neovim');

  await verify.click();
  const result = page.getByTestId('scenario-verify-result');
  await expect(result).toHaveClass(/failed/, { timeout: 60_000 });

  // Clicking the step's command puts it in the desktop's terminal, not run.
  await page.locator('.exec-command').filter({ hasText: 'echo bureau' }).click();
  await expect.poll(() => desktopText(page)).toContain('echo bureau > /tmp/bureau.txt');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(8_000); // the check limiter
  await verify.click();
  await expect(page.getByTestId('scenario-completed')).toBeVisible({ timeout: 60_000 });
  await shot('4-completed');

  expect(outside, 'the desktop asks no outside site').toEqual([]);
});

test('a reload rebuilds a desktop run at its step on a new desktop, and a second tab stands aside', async ({ page, context }) => {
  test.skip(!admin, 'needs the platform admin to set up the lab');
  test.setTimeout(10 * 60 * 1000);
  await login(page, LEARNER_EMAIL, PASSWORD);
  await dismissVerificationBanner(page);
  await navigateViaMenuCategory(page, 'scenarios', '/scenarios');
  const card = page.getByTestId('scenario-card').filter({ hasText: TITLE_RELOAD });
  await expect(card).toBeVisible({ timeout: 15_000 });
  await card.getByTestId('scenario-launch-btn').click();
  await page.waitForURL(/\/terminal-session\//, { timeout: 240_000 });
  const first = page.url().split('/terminal-session/')[1];

  const desktop = page.frameLocator('iframe.ocf-desktop-frame');
  await expect(page.getByTestId('scenario-verify-btn')).toBeEnabled({ timeout: 300_000 });
  await expect(desktop.locator('#win-terminal-1')).toBeVisible({ timeout: 120_000 });
  await typeOnDesktop(page, 'echo moi > /tmp/moi.txt');
  await expect.poll(() => desktopText(page)).toContain('echo moi > /tmp/moi.txt');

  await page.reload();
  await page.waitForURL((url) => /\/terminal-session\/local-/.test(url.pathname) && !url.pathname.endsWith(first), { timeout: 120_000 });
  await expect(page.getByTestId('scenario-verify-btn')).toBeEnabled({ timeout: 300_000 });
  await expect(desktop.locator('#win-terminal-1')).toBeVisible({ timeout: 120_000 });
  await expect(page.locator('iframe.ocf-desktop-frame')).toHaveCount(1);

  // A second tab on the run is told the first one has it; the first keeps its desktop.
  const second = await context.newPage();
  await login(second, LEARNER_EMAIL, PASSWORD);
  await second.goto(page.url());
  await expect(second.getByText('Ouvert dans un autre onglet')).toBeVisible({ timeout: 60_000 });
  await expect(second.locator('iframe.ocf-desktop-frame')).toHaveCount(0);
  await second.close();
  await expect(desktop.locator('#win-terminal-1')).toBeVisible();

  // The world was rebuilt, the learner's file is gone.
  await page.getByTestId('scenario-verify-btn').click();
  const result = page.getByTestId('scenario-verify-result');
  await expect(result).toHaveClass(/failed/, { timeout: 60_000 });
  await expect(result.locator('.output-text')).toContainText('/tmp/moi.txt manque');

  await typeOnDesktop(page, 'echo moi > /tmp/moi.txt');
  await page.waitForTimeout(8_000); // the check limiter
  await page.getByTestId('scenario-verify-btn').click();
  await expect(page.getByTestId('scenario-completed')).toBeVisible({ timeout: 60_000 });
  await page.screenshot({ path: test.info().outputPath('desktop-reload-completed.png') });
});
