import { test, expect } from '@playwright/test';
import { login } from './helpers/auth';
import { dismissVerificationBanner, navigateViaMenuCategory } from './helpers/ui';
import { apiLogin, importScenario, deleteScenarioById, cleanupScenarioSession, getMyScenarioSessions, type ApiSession } from './helpers/scenarioApi';
import { adminSession } from './helpers/freshUsers';

/**
 * A lab in the learner's browser that offers apps shows unkernel's desktop in
 * the console's place. Its launcher lists the apps the scenario offers and
 * nothing else (no games), the page asks no outside site for its wallpaper,
 * and « Vérifier » checks what the learner did in the desktop's terminal.
 *
 * Needs the desktop page under public/unkernel-desktop/ (local-machine-image,
 * desktop/build.sh).
 */

const API = process.env.OCF_API_URL || 'http://localhost:8080/api/v1';
const LEARNER_EMAIL = process.env.E2E_USER || 'karim@test.ocf';
const PASSWORD = process.env.E2E_PASS || 'OcfTest2026!';
const TITLE = `E2E local desktop ${Date.now().toString(36)}`;

let admin: ApiSession | null = null;
let learner: ApiSession;
let scenarioId = '';
let planId = '';
let planSettingBefore = 'off';

test.beforeAll(async () => {
  admin = await adminSession();
  learner = await apiLogin(LEARNER_EMAIL, PASSWORD);
  if (!admin) return;
  const asAdmin = { Authorization: `Bearer ${admin.token}` };

  const flags = await admin.api.get(`${API}/features?key=local_machines`, { headers: asAdmin });
  const flag = (await flags.json()).data.find((f: { key: string }) => f.key === 'local_machines');
  expect((await admin.api.patch(`${API}/features/${flag.id}`, { headers: asAdmin, data: { enabled: true } })).ok()).toBeTruthy();

  const current = await learner.api.get(`${API}/user-subscriptions/current`, { headers: { Authorization: `Bearer ${learner.token}` } });
  const subscription = await current.json();
  planId = subscription.subscription_plan_id;
  planSettingBefore = subscription.subscription_plan?.local_machines || 'off';
  expect((await admin.api.patch(`${API}/subscription-plans/${planId}`, { headers: asAdmin, data: { local_machines: 'allowed' } })).ok()).toBeTruthy();

  scenarioId = (await importScenario(admin, null, {
    title: TITLE,
    description: 'Auto-generated by local-machine-desktop.spec.ts — safe to delete.',
    is_public: true,
    machine: 'local',
    machine_apps: ['python', 'nvim'],
    steps: [{
      title: 'Écrire depuis le bureau',
      step_type: 'terminal',
      text_content: 'Dans le terminal du bureau, écrivez `bureau` dans `/tmp/bureau.txt`.',
      verify_script: 'grep -qx bureau /tmp/bureau.txt || { echo "/tmp/bureau.txt manque"; exit 1; }',
    }],
  })).id;
});

test.afterAll(async () => {
  if (!admin) return;
  for (const s of await getMyScenarioSessions(learner)) {
    if (s.scenario_id === scenarioId) await cleanupScenarioSession(learner, s.id);
  }
  if (scenarioId) await deleteScenarioById(admin, scenarioId);
  await admin.api.patch(`${API}/subscription-plans/${planId}`, {
    headers: { Authorization: `Bearer ${admin.token}` }, data: { local_machines: planSettingBefore },
  });
});

test('a lab that offers apps shows the desktop, with only those apps to install', async ({ page }, info) => {
  test.skip(!admin, 'needs the platform admin to set up the lab');
  test.setTimeout(10 * 60 * 1000);
  const shot = (name: string) => page.screenshot({ path: info.outputPath(`${name}.png`) });
  const outside: string[] = [];
  page.on('request', r => { if (/picsum\.photos|unkernel\.dev/.test(r.url())) outside.push(r.url()); });

  await login(page, LEARNER_EMAIL, PASSWORD);
  await dismissVerificationBanner(page);
  await navigateViaMenuCategory(page, 'scenarios', '/scenarios');
  const card = page.getByTestId('scenario-card').filter({ hasText: TITLE });
  await expect(card).toBeVisible({ timeout: 15_000 });
  await card.getByTestId('scenario-launch-btn').click();
  await page.waitForURL(/\/terminal-session\//, { timeout: 240_000 });

  const verify = page.getByTestId('scenario-verify-btn');
  await expect(verify).toBeEnabled({ timeout: 300_000 });
  const desktop = page.frameLocator('iframe.ocf-desktop-frame');
  await expect(desktop.locator('#win-terminal-1')).toBeVisible({ timeout: 120_000 });
  await shot('1-desktop');

  await desktop.locator('#win-terminal-1 .wm-body').click();
  await page.keyboard.press('Control+Shift+O');
  // The launcher shows the page's own apps and a folder per group that has an
  // offered app: Tools (Neovim) and Runtimes (Python), and no other group.
  const tile = (name: string) => desktop.getByText(name, { exact: true });
  await expect(tile('Runtimes')).toBeVisible({ timeout: 10_000 });
  await expect(tile('Tools')).toBeVisible();
  for (const absent of ['Games', 'Browsers', 'Agents', 'Media', 'Servers']) {
    await expect(tile(absent)).toHaveCount(0);
  }
  // Its search finds an offered app, and nothing for a game.
  await page.keyboard.type('python');
  await expect(tile('Python')).toBeVisible();
  await page.keyboard.press('Control+A');
  await page.keyboard.type('doom');
  await expect(tile('Doom')).toHaveCount(0);
  await expect(tile('Python')).toHaveCount(0);
  await shot('2-launcher');
  // The first Escape clears the search, the second closes the launcher.
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');
  await expect(desktop.getByPlaceholder('Search')).toHaveCount(0);

  await verify.click();
  const result = page.getByTestId('scenario-verify-result');
  await expect(result).toHaveClass(/failed/, { timeout: 60_000 });

  await desktop.locator('#win-terminal-1 .wm-body').click();
  await page.keyboard.type('echo bureau > /tmp/bureau.txt\n', { delay: 30 });
  await page.waitForTimeout(8_000); // the check limiter
  await verify.click();
  await expect(page.getByTestId('scenario-completed')).toBeVisible({ timeout: 60_000 });
  await shot('3-completed');

  expect(outside, 'the desktop asks no outside site').toEqual([]);
});
