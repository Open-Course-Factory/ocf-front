import { test, expect, type Page } from '@playwright/test';
import { loginFresh, switchToOrg } from './helpers/auth';
import { dismissVerificationBanner } from './helpers/ui';
import {
  apiLogin,
  findOwnedTeamOrg,
  findTeacherGroup,
  importScenario,
  deleteScenario,
  createGroupAssignment,
  deleteAssignment,
  launchScenarioSession,
  cleanupScenarioSession,
  ensureOrgMembership,
  removeOrgMembership,
  getUserId,
  type ApiSession,
} from './helpers/scenarioApi';

// ---------------------------------------------------------------------------
// Tier B — a trainer opens a learner's session page from the live wall (#385).
//
// marc teaches a class karim belongs to. karim is at work on a scenario of the
// class; marc opens the class's live wall, focuses karim's tile, and follows
// "Open session page" to karim's full session page in supervisor mode
// (/terminal-session/<id>?group=<classId>): karim's screen in the supervision
// viewer, karim's name in the header, and the run's progress.
//
// Fixture setup mirrors scenario-teacher.spec.ts: a per-run scenario assigned
// to marc's class, karim made a member of marc's org for the run (adding him to
// the class does not), and karim's run launched through the API. Setup and
// teardown go through the API; the behavior under test stays in the UI.
// ---------------------------------------------------------------------------

const TRAINER_EMAIL = process.env.E2E_TRAINER_EMAIL || 'marc@test.ocf';
const LEARNER_EMAIL = process.env.E2E_USER || 'karim@test.ocf';
const PASSWORD = process.env.E2E_PASS || 'OcfTest2026!';

const RUN_STAMP = Date.now().toString(36);
const FIXTURE_TITLE = `E2E supervisor page ${RUN_STAMP}`;

let trainer: ApiSession;
let learner: ApiSession;
let learnerId = '';
let orgId: string | null = null;
let orgDisplayName = '';
let groupId: string | null = null;
let scenarioId: string | null = null;
let assignmentId: string | null = null;
let learnerTerminalId: string | null = null;
let grantedMembership: string | null = null;

/** The class console, in the org that owns the class (My Classes is org-scoped). */
async function openClassConsole(page: Page): Promise<void> {
  await loginFresh(page, TRAINER_EMAIL, PASSWORD);
  await dismissVerificationBanner(page);
  await switchToOrg(page, orgDisplayName);
  await page.locator('.main-menu .my-classes-header').click();
}

test.beforeAll(async () => {
  trainer = await apiLogin(TRAINER_EMAIL, PASSWORD);
  learner = await apiLogin(LEARNER_EMAIL, PASSWORD);
  learnerId = await getUserId(learner);

  const org = await findOwnedTeamOrg(trainer);
  const group = await findTeacherGroup(trainer, /docker fondamentaux/i, 2);
  if (!org || !group) return;
  orgId = org.id;
  orgDisplayName = org.displayName;
  groupId = group.group_id;

  grantedMembership = await ensureOrgMembership(trainer, orgId, learnerId);

  const scenario = await importScenario(trainer, orgId, {
    title: FIXTURE_TITLE,
    description: 'Auto-generated by supervisor-session-page.spec.ts — safe to delete.',
    is_public: false,
    steps: [{ title: 'Read the briefing', step_type: 'info', text_content: 'Nothing to do.' }],
  });
  scenarioId = scenario.id;
  assignmentId = (await createGroupAssignment(trainer, scenarioId, groupId)).id;

  const launched = await launchScenarioSession(learner, scenarioId, orgId);
  learnerTerminalId = launched?.terminal_session_id ?? null;
});

test.afterAll(async () => {
  if (scenarioId) await cleanupScenarioSession(learner, scenarioId).catch(() => {});
  if (assignmentId) await deleteAssignment(trainer, assignmentId);
  if (orgId && scenarioId) await deleteScenario(trainer, orgId, scenarioId);
  if (grantedMembership) await removeOrgMembership(trainer, grantedMembership);
  await trainer?.api.dispose();
  await learner?.api.dispose();
});

test("the trainer opens a learner's session page from the live wall and watches it", async ({ page }) => {
  test.skip(!groupId, `${TRAINER_EMAIL} teaches no class with learners — seed the dev personas first`);
  test.skip(!learnerTerminalId, 'the learner run could not be provisioned — likely host capacity');
  test.setTimeout(300_000);

  await openClassConsole(page);
  const classRow = page.locator('[data-test="class-row"]').filter({ hasText: FIXTURE_TITLE });
  await expect(classRow).toBeVisible({ timeout: 20_000 });
  await classRow.click();

  // The wall, and karim's tile on it.
  await page.getByRole('tab', { name: /mur|wall/i }).click();
  const tile = page.locator(`.live-sessions-tile[data-session-id="${learnerTerminalId}"]`);
  await expect(tile).toBeVisible({ timeout: 60_000 });
  const learnerName = (await tile.locator('.supervision-viewer-name').innerText()).trim();
  expect(learnerName, 'the wall names the learner, not their id').not.toBe(learnerId);

  // Focus the tile, then follow the link to the full session page.
  await tile.locator('.supervision-viewer').click();
  const openPage = page.getByTestId('open-session-page');
  await expect(openPage).toBeVisible({ timeout: 20_000 });
  await openPage.click();

  await expect(page).toHaveURL(
    new RegExp(`/terminal-session/${learnerTerminalId}\\?group=${groupId}$`),
    { timeout: 20_000 }
  );

  // Supervisor mode: the learner's name, their live screen, their progress.
  await expect(page.getByTestId('supervisor-learner-name')).toContainText(learnerName, { timeout: 30_000 });
  const viewer = page.locator('.supervision-viewer');
  await expect(viewer).toBeVisible();
  await expect(viewer.locator('.xterm')).toBeVisible({ timeout: 60_000 });
  await expect(page.getByTestId('supervisor-progress')).toContainText(FIXTURE_TITLE, { timeout: 30_000 });

  // Not the learner's page: none of the learner's own controls, no not-found state.
  await expect(page.locator('.error-section')).toHaveCount(0);
  await expect(page.getByTestId('scenario-abandon-btn')).toHaveCount(0);
  // The learner console (stop / delete / extend / sharing / ports) is not mounted.
  await expect(page.locator('.terminal-session-panel')).toHaveCount(0);
});
