import { test, expect, type Page } from '@playwright/test';
import { login } from './helpers/auth';
import { dismissVerificationBanner } from './helpers/ui';
import { apiLogin, type ApiSession } from './helpers/scenarioApi';

/**
 * Assigning a plan to an organization from the admin panel.
 *
 * The confirmation used to appear inside the scrolling form, below the fold, and
 * the button just clicked disappeared, so the click looked dead and nothing was
 * saved. The viewport is short on purpose: the form overflows it, as in production.
 */

const ADMIN_EMAIL = process.env.E2E_ADMIN_EMAIL || '1.supervisor@test.com';
const ADMIN_PASSWORD = process.env.E2E_ADMIN_PASSWORD || 'test';
const API_BASE = process.env.OCF_API_URL || 'http://localhost:8080/api/v1';

const RUN_STAMP = Date.now().toString(36);
const ORG_NAME = `E2E plan assign ${RUN_STAMP}`;
const PLAN_NAME = `E2E assignable plan ${RUN_STAMP}`;

let admin: ApiSession;
let orgId: string;
let planId: string;

function authHeaders() {
  return { Authorization: `Bearer ${admin.token}` };
}

async function createEntity(path: string, data: Record<string, unknown>): Promise<string> {
  const res = await admin.api.post(`${API_BASE}${path}`, { headers: authHeaders(), data });
  if (!res.ok()) throw new Error(`POST ${path} failed: ${res.status()} ${await res.text()}`);
  return (await res.json()).id;
}

/** Administration → System → Organizations, through the sidebar. */
async function openAdminOrganizations(page: Page): Promise<void> {
  const adminLink = page.locator('.admin-link');
  if (!(await adminLink.isVisible().catch(() => false))) {
    await page.locator('.menu-bottom-toggle').click();
  }
  await adminLink.click();
  const category = page.locator('.nav-menu-shell [data-category="system"]');
  await expect(category).toBeVisible();
  const itemList = category.locator('.category-items');
  if (!(await itemList.evaluate((el) => el.classList.contains('expanded')))) {
    await category.locator('.category-header').click();
    await expect(itemList).toHaveClass(/expanded/);
  }
  await category.locator('a[href="/admin/organizations"]').click();
}

test.beforeAll(async () => {
  admin = await apiLogin(ADMIN_EMAIL, ADMIN_PASSWORD);
  planId = await createEntity('/subscription-plans', {
    name: PLAN_NAME,
    description: 'Auto-generated by admin-org-plan-assign.spec.ts — safe to delete.',
    price_amount: 0,
    currency: 'eur',
    billing_interval: 'month',
    priority: 7,
    is_active: true,
    max_cpu: 1000,
    max_memory_mb: 1024,
    group_management_enabled: true,
  });
  orgId = await createEntity('/organizations', {
    name: ORG_NAME.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    display_name: ORG_NAME,
    description: 'Auto-generated by admin-org-plan-assign.spec.ts — safe to delete.',
  });
});

test.afterAll(async () => {
  if (orgId) await admin.api.delete(`${API_BASE}/organizations/${orgId}`, { headers: authHeaders() });
  if (planId) await admin.api.delete(`${API_BASE}/subscription-plans/${planId}`, { headers: authHeaders() });
  await admin?.api.dispose();
});

test('an administrator can assign a plan without scrolling to find the confirmation', async ({ page }) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 1280, height: 600 });

  await login(page, ADMIN_EMAIL, ADMIN_PASSWORD);
  await dismissVerificationBanner(page);
  await openAdminOrganizations(page);

  await page.getByPlaceholder(/Search organizations|Rechercher des organisations/).fill(ORG_NAME);
  const row = page.locator('tr, li').filter({ hasText: ORG_NAME }).first();
  await row.locator('button').filter({ has: page.locator('.fa-credit-card') }).click();

  const modal = page.locator('.base-modal-container').filter({ hasText: ORG_NAME });
  await modal.locator('#plan-select').selectOption(planId);

  const primaryButton = modal.locator('.ocf-plan-footer-actions .btn-primary');
  await primaryButton.click();

  const summary = modal.locator('.confirm-assign');
  await expect(summary).toBeInViewport();
  await expect(summary).toContainText(ORG_NAME);
  await expect(primaryButton).toBeInViewport();

  const subscribe = page.waitForRequest(
    (req) => req.method() === 'POST' && req.url().includes(`/organizations/${orgId}/subscribe`)
  );
  await primaryButton.click();
  expect((await subscribe).postDataJSON().subscription_plan_id).toBe(planId);
  await expect(modal.locator('.success-message')).toBeInViewport();
});
