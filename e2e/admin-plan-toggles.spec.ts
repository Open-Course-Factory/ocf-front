import { test, expect, type Page } from '@playwright/test';
import { login } from './helpers/auth';
import { dismissVerificationBanner } from './helpers/ui';
import { apiLogin, type ApiSession } from './helpers/paymentApi';

/**
 * Network access and data persistence on Administration → Subscription plans.
 *
 * That page renders PlanConfigModal in Entity.vue's modal slot, so the store's
 * fieldList never reaches it: a capability the modal has no checkbox for
 * cannot be changed by an administrator. What is pinned here is that both
 * checkboxes reach the saved plan, survive a reload, and that a toggle edit
 * leaves the rest of the plan alone (a partial SubscriptionPlan PATCH once
 * blanked every field it did not carry).
 */

const ADMIN_EMAIL = process.env.E2E_ADMIN_EMAIL || '1.supervisor@test.com';
const ADMIN_PASSWORD = process.env.E2E_ADMIN_PASSWORD || 'test';
const API_BASE = process.env.OCF_API_URL || 'http://localhost:8080/api/v1';

const PLAN_NAME = `E2E plan toggles ${Date.now().toString(36)}`;

let admin: ApiSession;
let planId: string | null = null;

function authHeaders() {
  return { Authorization: `Bearer ${admin.token}` };
}

async function getPlan(id: string): Promise<any> {
  const res = await admin.api.get(`${API_BASE}/subscription-plans/${id}`, { headers: authHeaders() });
  if (!res.ok()) throw new Error(`get plan failed: ${res.status()} ${await res.text()}`);
  return res.json();
}

/** Administration → Billing → Subscription plans, through the sidebar. */
async function openAdminPlans(page: Page): Promise<void> {
  const adminLink = page.locator('.admin-link');
  if (!(await adminLink.isVisible().catch(() => false))) {
    await page.locator('.menu-bottom-toggle').click();
  }
  await adminLink.click();
  const category = page.locator('.nav-menu-shell [data-category="billing"]');
  await expect(category).toBeVisible();
  const itemList = category.locator('.category-items');
  if (!(await itemList.evaluate((el) => el.classList.contains('expanded')))) {
    await category.locator('.category-header').click();
    await expect(itemList).toHaveClass(/expanded/);
  }
  await category.locator('a[href="/admin/subscription-plans"]').click();
}

async function openPlanEditor(page: Page): Promise<void> {
  const row = page.locator('li.entity-item').filter({ hasText: PLAN_NAME });
  await expect(row).toBeVisible({ timeout: 15_000 });
  await row.locator('button.btn-primary').filter({ has: page.locator('.fa-edit') }).click();
  await expect(page.locator('[data-test="plan-save-button"]')).toBeVisible();
}

test.beforeAll(async () => {
  admin = await apiLogin(ADMIN_EMAIL, ADMIN_PASSWORD);
  const res = await admin.api.post(`${API_BASE}/subscription-plans`, {
    headers: authHeaders(),
    data: {
      name: PLAN_NAME,
      description: 'Auto-generated by admin-plan-toggles.spec.ts — safe to delete.',
      price_amount: 0,
      currency: 'eur',
      billing_interval: 'month',
      priority: 7,
      is_active: true,
      max_cpu: 1000,
      max_memory_mb: 1024,
      session_supervision_enabled: true,
    },
  });
  if (!res.ok()) throw new Error(`create plan failed: ${res.status()} ${await res.text()}`);
  planId = (await res.json()).id;
});

test.afterAll(async () => {
  if (planId) {
    await admin.api.delete(`${API_BASE}/subscription-plans/${planId}`, { headers: authHeaders() });
  }
  await admin?.api.dispose();
});

test('network access and data persistence toggles save, survive a reload and keep the rest of the plan', async ({
  page,
}) => {
  test.setTimeout(120_000);

  await login(page, ADMIN_EMAIL, ADMIN_PASSWORD);
  await dismissVerificationBanner(page);
  await openAdminPlans(page);
  await openPlanEditor(page);

  const network = page.locator('[data-test="plan-network-access-toggle"]');
  const persistence = page.locator('[data-test="plan-data-persistence-toggle"]');
  await expect(network).not.toBeChecked();
  await expect(persistence).not.toBeChecked();

  await network.check();
  await persistence.check();
  const patch = page.waitForRequest(
    (req) => req.method() === 'PATCH' && req.url().includes(`/subscription-plans/${planId}`)
  );
  await page.locator('[data-test="plan-save-button"]').click();
  const sent = (await patch).postDataJSON();
  expect(sent.network_access_enabled).toBe(true);
  expect(sent.data_persistence_enabled).toBe(true);
  await expect(page.locator('[data-test="plan-save-button"]')).toBeHidden();

  await page.reload();
  await openPlanEditor(page);
  await expect(network, 'network access survives a reload').toBeChecked();
  await expect(persistence, 'data persistence survives a reload').toBeChecked();

  // Turning one off must not drag the other, or anything else, with it.
  await persistence.uncheck();
  await page.locator('[data-test="plan-save-button"]').click();
  await expect(page.locator('[data-test="plan-save-button"]')).toBeHidden();

  await expect.poll(async () => (await getPlan(planId!)).data_persistence_enabled).toBe(false);
  const saved = await getPlan(planId!);
  expect(saved.network_access_enabled).toBe(true);
  expect(saved.name).toBe(PLAN_NAME);
  expect(saved.priority).toBe(7);
  expect(saved.is_active).toBe(true);
  expect(saved.max_cpu).toBe(1000);
  expect(saved.max_memory_mb).toBe(1024);
  expect(saved.session_supervision_enabled).toBe(true);
});
