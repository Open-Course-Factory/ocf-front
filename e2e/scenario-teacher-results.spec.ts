import { test, expect, type Page } from '@playwright/test';
import { login, loginFresh, switchToOrg } from './helpers/auth';
import { dismissVerificationBanner, navigateViaMenuCategory } from './helpers/ui';
import {
  apiLogin,
  findOwnedTeamOrg,
  findTeacherGroup,
  importScenario,
  deleteScenario,
  createGroupAssignment,
  deleteAssignment,
  getAvailableScenario,
  getMyScenarioSessions,
  cleanupScenarioSession,
  type ApiSession,
} from './helpers/scenarioApi';
import { readFlagFromTerminal, typeInTerminal, waitForLiveTerminal } from './helpers/xterm';

// ---------------------------------------------------------------------------
// Tier B — what the trainer sees after a learner has actually finished.
//
// karim runs the four-step fixture to the end, then marc reads the two places
// the run surfaces: the class analytics (one completion on the scenario's row)
// and the learner's session detail, where the commands typed in the container
// are replayed.
//
// The command assertion is deliberately fuzzy — history is reconstructed from
// terminal echo, so it over-records (prompts, partial lines). What it must
// never do is come back empty for a learner who spent the session typing.
//
// The analytics page only knows about ASSIGNED scenarios — it walks the group's
// assignments and asks for each one's figures — so the fixture is assigned even
// though it is public and karim could reach it either way.
// ---------------------------------------------------------------------------

const TRAINER_EMAIL = process.env.E2E_TRAINER_EMAIL || 'marc@test.ocf';
const LEARNER_EMAIL = process.env.E2E_USER || 'karim@test.ocf';
const PASSWORD = process.env.E2E_PASS || 'OcfTest2026!';

const RUN_STAMP = Date.now().toString(36);
const FIXTURE_TITLE = `E2E results ${RUN_STAMP}`;

let trainer: ApiSession;
let learner: ApiSession;
let orgId: string | null = null;
let orgDisplayName = '';
let groupId: string | null = null;
let scenarioId: string | null = null;
let assignmentId: string | null = null;
let launchable = false;
let completed = false;

test.describe.configure({ mode: 'serial' });

/** Open the fixture's class from the console, in the org context that lists it. */
async function openFixtureClass(page: Page): Promise<void> {
  await loginFresh(page, TRAINER_EMAIL, PASSWORD);
  await dismissVerificationBanner(page);
  await switchToOrg(page, orgDisplayName);
  await page.locator('.main-menu .my-classes-header').click();
  const classRow = page.locator('[data-test="class-row"]').filter({ hasText: FIXTURE_TITLE });
  await expect(classRow).toBeVisible({ timeout: 20_000 });
  await classRow.click();
}

test.beforeAll(async () => {
  trainer = await apiLogin(TRAINER_EMAIL, PASSWORD);
  learner = await apiLogin(LEARNER_EMAIL, PASSWORD);

  const org = await findOwnedTeamOrg(trainer);
  const group = await findTeacherGroup(trainer, /docker fondamentaux/i, 2);
  if (!org || !group) return;
  orgId = org.id;
  orgDisplayName = org.displayName;
  groupId = group.group_id;

  const scenario = await importScenario(trainer, orgId, {
    title: FIXTURE_TITLE,
    description: 'Auto-generated by scenario-teacher-results.spec.ts — safe to delete.',
    is_public: true,
    flags_enabled: true,
    steps: [
      { title: 'Read the briefing', step_type: 'info', text_content: 'Just read and continue.' },
      {
        title: 'Touch a file',
        step_type: 'terminal',
        text_content: 'Run `touch /tmp/e2e-marker` in the terminal.',
      },
      {
        title: 'Capture the flag',
        step_type: 'flag',
        has_flag: true,
        text_content: 'The flag hides in /tmp — cat it and submit.',
      },
      {
        title: 'Final quiz',
        step_type: 'quiz',
        show_immediate_feedback: true,
        questions: [
          {
            order: 1,
            question_text: 'Does `ls` list files?',
            question_type: 'true_false',
            correct_answer: 'true',
            points: 1,
          },
        ],
      },
    ],
  });
  scenarioId = scenario.id;

  const assignment = await createGroupAssignment(trainer, scenarioId, groupId);
  assignmentId = assignment.id;

  launchable = !!(await getAvailableScenario(learner, FIXTURE_TITLE))?.launchable;
});

test.afterAll(async () => {
  if (scenarioId) {
    await cleanupScenarioSession(learner, scenarioId).catch(() => {});
    if (orgId) await deleteScenario(trainer, orgId, scenarioId);
  }
  if (assignmentId) await deleteAssignment(trainer, assignmentId);
  await trainer?.api.dispose();
  await learner?.api.dispose();
});

test('the learner works through the whole scenario in the real container', async ({ page }) => {
  test.skip(!groupId, `${TRAINER_EMAIL} teaches no class with learners — seed the dev personas first`);
  test.skip(
    !launchable,
    'fixture not launchable — Tier B needs a live tt-backend + Incus with an apk distribution'
  );
  test.setTimeout(360_000);

  await login(page, LEARNER_EMAIL, PASSWORD);
  await dismissVerificationBanner(page);
  await navigateViaMenuCategory(page, 'terminals', '/scenarios');

  const card = page.getByTestId('scenario-card').filter({ hasText: FIXTURE_TITLE });
  await expect(card).toBeVisible({ timeout: 15_000 });
  await card.getByTestId('scenario-launch-btn').click();

  const errorToast = page.locator('.el-notification');
  await Promise.race([
    page.waitForURL(/\/terminal-session\//, { timeout: 240_000 }),
    errorToast.waitFor({ state: 'visible', timeout: 240_000 }),
  ]);
  if (!/\/terminal-session\//.test(page.url())) {
    test.skip(true, 'launch refused by the backend (likely host capacity)');
  }

  const stepTitle = page.getByTestId('scenario-step-title');
  await expect(stepTitle).toHaveText('Read the briefing', { timeout: 60_000 });
  await page.getByTestId('scenario-info-ack').click();

  await expect(stepTitle).toHaveText('Touch a file', { timeout: 30_000 });
  await waitForLiveTerminal(page);
  await typeInTerminal(page, 'touch /tmp/e2e-marker');
  await page.getByTestId('scenario-verify-btn').click();

  await expect(stepTitle).toHaveText('Capture the flag', { timeout: 30_000 });
  const session = (await getMyScenarioSessions(learner)).find((s: any) => s.scenario_id === scenarioId);
  expect(session, 'the learner should have a session by now').toBeTruthy();
  const flag = await readFlagFromTerminal(page, session.current_step);
  await page.getByTestId('scenario-flag-input').fill(flag);
  await page.getByTestId('scenario-flag-submit').click();

  await expect(stepTitle).toHaveText('Final quiz', { timeout: 30_000 });
  await page.getByTestId('quiz-option').filter({ hasText: /vrai|true/i }).first().click();
  await page.getByTestId('quiz-submit').click();
  await expect(page.getByTestId('quiz-results-score')).toBeVisible({ timeout: 15_000 });
  await page.getByTestId('quiz-finish').click();

  await expect(page.getByTestId('scenario-completed')).toBeVisible({ timeout: 30_000 });
  completed = true;
});

test('the class analytics count the completion', async ({ page }) => {
  test.skip(!completed, 'no run was completed, so there is nothing to report on');
  test.setTimeout(180_000);

  await openFixtureClass(page);
  await page.locator('.class-nav a[href$="/analytics"]').click();

  const row = page.locator('.analytics-table tbody tr').filter({ hasText: FIXTURE_TITLE });
  await expect(row).toBeVisible({ timeout: 30_000 });
  // Columns: scenario, difficulty, started, completed, rate, avg grade, avg time.
  await expect(row.locator('td').nth(3)).toHaveText('1');
});

test('the learner session detail replays the commands typed in the container', async ({ page }) => {
  test.skip(!completed, 'no run was completed, so there is nothing to replay');
  test.setTimeout(180_000);

  await openFixtureClass(page);
  await page.locator('.class-nav a[href$="/scenarios"]').click();

  const assignmentCard = page.locator('.assignment-card').filter({ hasText: FIXTURE_TITLE });
  await expect(assignmentCard).toBeVisible({ timeout: 20_000 });
  await assignmentCard.locator('.btn-view-results').click();

  const resultRow = page.locator('.results-table tbody tr').first();
  await expect(resultRow).toBeVisible({ timeout: 30_000 });
  await resultRow.locator('.actions-cell .btn').first().click();

  await page.locator('#detail-tab-commands').click();
  const commands = page.locator('.commands-cmd-text');
  await expect(commands.first()).toBeVisible({ timeout: 30_000 });

  // Fuzzy on purpose: echo-reconstructed history over-records, so the claim is
  // that the `cat` the learner ran to read the flag is in there somewhere.
  const replayed = (await commands.allInnerTexts()).join('\n');
  expect(replayed, 'the flag-reading cat should appear in the replay').toContain('cat');
});
